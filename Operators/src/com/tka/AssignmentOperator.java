package com.tka;

public class AssignmentOperator {
	public static void main(String args[]) {
		int a = 25;
		a++;  // use a = 25 and store a = 26
		a+=a+7;  //  26+7 = 33 +26
		System.out.println(a);
		System.out.println(a++); //use 59 and store 60
		System.out.println(a--); // use 60 and store 59
		System.out.println(++a); //use 60 
		
	}

}
