package com.tka;

public class IncrementDecrement {
	public static void main(String args[]) {
		int a =10;
		a++; //11
		
		System.out.println(a);  // use 11 
		System.out.println(a++); // use 11 and store 12
		System.out.println(++a); //use 13 
		
		a++; //14
		a--; //13
		System.out.println(a++); // use 13 and store 15
		System.out.println(a+7); // 15+7 
		System.out.println(a-5); //14 - 9
		
		
		
	}

}
