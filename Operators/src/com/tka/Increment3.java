package com.tka;

public class Increment3 {
	public static void main(String args[]) {
		int i =10;
		i++;  //11
		System.out.println(i++); //11 and store 12
		i--; //11
		i++; // print 11 and store 12
		System.out.println(i--); //print 12 and store 11
		i++; //print 11 and store 12
		i--; //print 12 and store 11 
		System.out.println(i++); //print 11 and store 12
		i++; // print 12 and store 13
		i--; // print 13 and store 12
		System.out.println(i++); //print 12 and store 13
		i++; // print 13 and store 14
		System.out.println(i+7); //use i = 14 +7 = 21
		i--; // print 14 and store 13
		i++; // print 13 and store 14
		System.out.println(i+8); // use i = 14 +8 = 22
		
		
		
	
	}

}
