package com.tka;

public class Increment1 {

    public static void main(String[] args) {

        int a = 10;

        System.out.println(a++);  //use 10 and store 11
        System.out.println(++a);  //use 12 
        System.out.println(a--);  //use use 12 and store 11
        System.out.println(--a);  // use 10 
        System.out.println(a);    //use 10
    }
}